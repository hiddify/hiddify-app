#!/usr/bin/env python3
"""Generates SpriteNet brand assets (Android vector drawables, legacy launcher
bitmaps and the Flutter logo SVG) from the logo geometry in spritenet_icon.svg.

Usage: python3 branding/generate_icons.py   (requires `pip install cairosvg pillow`)
"""

import io
from pathlib import Path

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"

CANVAS = "#0F0F11"
LIME = "#8DFF19"
LIME_LIGHT = "#C7FF55"

# Logo geometry, in the local coordinates of spritenet_icon.svg (inside translate(100 120)).
LINES = ["M175,12 L38,90 L175,168", "M115,78 L245,151 L115,226"]
STROKE = 28
DOTS = [(175, 12, 23), (38, 90, 23), (175, 168, 23), (115, 78, 21), (245, 151, 23), (115, 226, 23)]
# Bounding box including dot radius.
MIN_X, MIN_Y, MAX_X, MAX_Y = 15, -11, 268, 249
CX, CY = (MIN_X + MAX_X) / 2, (MIN_Y + MAX_Y) / 2
SIZE = max(MAX_X - MIN_X, MAX_Y - MIN_Y)


def circle_path(cx, cy, r):
    return f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0 Z"


def transform(viewport, logo_size):
    scale = logo_size / SIZE
    return scale, viewport / 2 - CX * scale, viewport / 2 - CY * scale


def lime_gradient():
    return (
        '<aapt:attr name="{attr}"><gradient android:type="linear" '
        f'android:startX="{MIN_X}" android:startY="{MIN_Y}" android:endX="{MAX_X}" android:endY="{MAX_Y}">'
        f'<item android:offset="0" android:color="{LIME_LIGHT}"/>'
        f'<item android:offset="1" android:color="{LIME}"/>'
        "</gradient></aapt:attr>"
    )


def vector(viewport, logo_size, *, size_dp=None, mono_color=None, glow=False):
    """Android VectorDrawable with the logo centered in a square viewport."""
    scale, tx, ty = transform(viewport, logo_size)
    size_dp = size_dp or viewport
    paths = []
    if glow:
        # VectorDrawable has no blur filter: emulate the neon glow with wide translucent strokes.
        for width, alpha in ((STROKE * 2.4, "22"), (STROKE * 1.7, "33")):
            for d in LINES:
                paths.append(
                    f'<path android:pathData="{d}" android:strokeColor="#{alpha}{LIME[1:]}" '
                    f'android:strokeWidth="{width}" android:strokeLineCap="round" android:strokeLineJoin="round"/>'
                )
    for d in LINES:
        if mono_color:
            paths.append(
                f'<path android:pathData="{d}" android:strokeColor="{mono_color}" android:strokeWidth="{STROKE}" '
                'android:strokeLineCap="round" android:strokeLineJoin="round"/>'
            )
        else:
            paths.append(
                f'<path android:pathData="{d}" android:strokeWidth="{STROKE}" '
                'android:strokeLineCap="round" android:strokeLineJoin="round">'
                + lime_gradient().format(attr="android:strokeColor")
                + "</path>"
            )
    dots = " ".join(circle_path(*c) for c in DOTS)
    if mono_color:
        paths.append(f'<path android:pathData="{dots}" android:fillColor="{mono_color}"/>')
    else:
        paths.append(f'<path android:pathData="{dots}">' + lime_gradient().format(attr="android:fillColor") + "</path>")

    body = "\n        ".join(paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/generate_icons.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
    <group android:scaleX="{scale:.5f}" android:scaleY="{scale:.5f}"
        android:translateX="{tx:.4f}" android:translateY="{ty:.4f}">
        {body}
    </group>
</vector>
"""


def svg(viewport, logo_size, *, background=None, radius=0, glow=False):
    """Plain SVG of the logo, used for Flutter and for rasterizing legacy icons."""
    scale, tx, ty = transform(viewport, logo_size)
    bg = f'<rect width="{viewport}" height="{viewport}" rx="{radius}" fill="{background}"/>' if background else ""
    glow_filter = ' filter="url(#glow)"' if glow else ""
    lines = "".join(f'<path d="{d}"/>' for d in LINES)
    dots = "".join(f'<circle cx="{x}" cy="{y}" r="{r}"/>' for x, y, r in DOTS)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{viewport}" height="{viewport}" viewBox="0 0 {viewport} {viewport}">
  <defs>
    <linearGradient id="lime" gradientUnits="userSpaceOnUse" x1="{MIN_X}" y1="{MIN_Y}" x2="{MAX_X}" y2="{MAX_Y}">
      <stop offset="0" stop-color="{LIME_LIGHT}"/>
      <stop offset="1" stop-color="{LIME}"/>
    </linearGradient>
    <filter id="glow" x="-60%" y="-60%" width="220%" height="220%">
      <feGaussianBlur stdDeviation="8" result="blur"/>
      <feMerge><feMergeNode in="blur"/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
  </defs>
  {bg}
  <g transform="translate({tx:.4f} {ty:.4f}) scale({scale:.5f})"{glow_filter}>
    <g fill="none" stroke="url(#lime)" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round">{lines}</g>
    <g fill="url(#lime)">{dots}</g>
  </g>
</svg>
"""


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    print("wrote", path.relative_to(ROOT))


def write_webp(path, svg_text, px, circle=False):
    png = cairosvg.svg2png(bytestring=svg_text.encode(), output_width=px, output_height=px)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    if circle:
        mask = Image.new("L", (px * 4, px * 4), 0)
        from PIL import ImageDraw

        ImageDraw.Draw(mask).ellipse((0, 0, px * 4 - 1, px * 4 - 1), fill=255)
        img.putalpha(mask.resize((px, px), Image.LANCZOS))
    img.save(path, "WEBP", lossless=True)
    print("wrote", path.relative_to(ROOT))


def main():
    # Adaptive launcher icon: 108dp canvas, 66dp safe zone.
    write(RES / "drawable/ic_launcher_foreground.xml", vector(108, 50, glow=True))
    write(RES / "drawable/ic_launcher_monochrome.xml", vector(108, 50, mono_color="#FFFFFFFF"))
    # Android 12+ splash icon is masked like an adaptive icon foreground.
    write(RES / "drawable/android12splash.xml", vector(108, 50, glow=True))
    # Pre-Android 12 splash logo.
    write(RES / "drawable/splash_logo.xml", vector(120, 120, glow=True))
    # Status bar / notification icon: must be single-color white.
    write(RES / "drawable/ic_stat_logo.xml", vector(24, 20, mono_color="#FFFFFFFF"))

    # Android TV banner (640x360): logo centered on the matte canvas background color.
    banner = vector(360, 220, glow=True).replace(
        'android:width="360dp"', 'android:width="640dp"').replace(
        'android:viewportWidth="360"', 'android:viewportWidth="640"')
    scale, tx, ty = transform(360, 220)
    banner = banner.replace(f'android:translateX="{tx:.4f}"', f'android:translateX="{tx + 140:.4f}"')
    write(RES / "drawable/ic_banner_foreground.xml", banner)
    logo_png = cairosvg.svg2png(bytestring=svg(360, 220, glow=True).encode(), output_width=360, output_height=360)
    banner_png = Image.new("RGBA", (640, 360), CANVAS)
    banner_png.alpha_composite(Image.open(io.BytesIO(logo_png)).convert("RGBA"), (140, 0))
    banner_png.save(RES / "mipmap-xhdpi/ic_banner.png")
    print("wrote", (RES / "mipmap-xhdpi/ic_banner.png").relative_to(ROOT))

    # Legacy launcher bitmaps (still packaged; used by some launchers and stores).
    densities = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    square = svg(512, 280, background=CANVAS, radius=116, glow=True)
    round_ = svg(512, 280, background=CANVAS, glow=True)
    for name, px in densities.items():
        write_webp(RES / f"mipmap-{name}/ic_launcher.webp", square, px)
        write_webp(RES / f"mipmap-{name}/ic_launcher_round.webp", round_, px, circle=True)

    # Flutter: flat logo (tinted at runtime with ColorFilter), and a full app icon.
    write(ROOT / "assets/images/logo.svg", svg(64, 60))
    write(ROOT / "assets/images/app_icon.svg", svg(512, 280, background=CANVAS, radius=116, glow=True))
    png = cairosvg.svg2png(bytestring=svg(512, 280, background=CANVAS, radius=116, glow=True).encode(), output_width=1024, output_height=1024)
    (ROOT / "branding/spritenet_icon_1024.png").write_bytes(png)
    print("wrote branding/spritenet_icon_1024.png")


if __name__ == "__main__":
    main()
